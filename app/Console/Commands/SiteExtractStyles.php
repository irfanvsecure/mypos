<?php

namespace App\Console\Commands;

use App\Site\HtmlOptimizer;
use Illuminate\Console\Command;
use Illuminate\Support\Facades\Http;

/**
 * Builds the inline-style map used by HtmlOptimizer and the matching CSS block in public/css/style.css.
 *
 * Fetches every page in the sitemap of --from (page content lives in the production database, so the
 * live site is the source of truth), collects each distinct style="…" value and gives it a stable class
 * name derived from its text. Existing map entries are kept, so a class never disappears while a page
 * might still use it. Then run `npm run minify`.
 *
 * Rules in style.css that select on the style attribute ([style], [style*="…"]) are repeated in the
 * generated block with the matching classes, so they keep applying once the attribute is gone.
 */
class SiteExtractStyles extends Command
{
    protected $signature = 'site:extract-styles
        {--from=https://mypos.pk : Site whose sitemap and pages are read}
        {--html-dir= : Read saved .html files from this folder instead of fetching}';

    protected $description = 'Map inline style attributes to classes and write their CSS into style.css';

    public const BEGIN = '/* ==== BEGIN generated by `php artisan site:extract-styles` — do not edit by hand ==== */';

    public const END = '/* ==== END generated inline styles ==== */';

    /** Properties that app.js changes through element.style at run time: an !important class would beat them. */
    private const JS_MANAGED = ['max-height', 'transform', '--rx', '--ry', '--mx', '--my'];

    public function handle(): int
    {
        $pages = $this->option('html-dir') ? $this->readDir($this->option('html-dir')) : $this->fetchSite(rtrim($this->option('from'), '/'));
        if ($pages === []) {
            $this->error('No pages read.');

            return self::FAILURE;
        }

        $values = [];
        foreach ($pages as $html) {
            foreach (self::styleValues($html) as $value) {
                $values[$value] = true;
            }
        }

        $mapPath = resource_path(HtmlOptimizer::MAP_FILE);
        $map = is_file($mapPath) ? (json_decode(file_get_contents($mapPath), true) ?: []) : [];
        $added = 0;
        foreach (array_keys($values) as $value) {
            if (isset($map[$value]) || ! self::extractable($value)) {
                continue;
            }
            $map[$value] = self::className($value);
            $added++;
        }

        $classes = array_count_values($map);
        if ($dupes = array_keys(array_filter($classes, fn ($n) => $n > 1))) {
            $this->error('Class name collision: ' . implode(', ', $dupes));

            return self::FAILURE;
        }

        ksort($map);
        @mkdir(dirname($mapPath), 0775, true);
        file_put_contents($mapPath, json_encode($map, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE) . "\n");

        $cssPath = public_path('css/style.css');
        $css = file_get_contents($cssPath);
        $source = self::withoutBlock($css);
        $block = self::BEGIN . "\n" . self::cssFor($map) . self::attributeRules($source, $map) . self::END . "\n";
        file_put_contents($cssPath, rtrim($source) . "\n\n" . $block);

        $this->info(count($pages) . ' pages, ' . count($values) . ' distinct style values, ' . count($map) . " mapped ($added new).");
        $this->line('Now run: npm run minify');

        return self::SUCCESS;
    }

    /** @return list<string> style attribute values outside <script>/<style>/comments, as HtmlOptimizer sees them */
    public static function styleValues(string $html): array
    {
        $html = preg_replace('#<(script|style)\b[^>]*>.*?</\1\s*>|<!--.*?-->#is', '', $html);
        preg_match_all('#<[a-zA-Z][^>]*?\sstyle\s*=\s*(?:"([^"]*)"|\'([^\']*)\')#s', $html, $m, PREG_SET_ORDER);

        return array_map(fn ($x) => ($x[1] ?? '') !== '' ? $x[1] : ($x[2] ?? ''), $m);
    }

    public static function extractable(string $value): bool
    {
        if (trim($value) === '' || str_contains($value, '{{') || str_contains($value, '<')) {
            return false;
        }
        foreach (self::declarations($value) as [$prop]) {
            if (in_array(strtolower($prop), self::JS_MANAGED, true)) {
                return false;
            }
        }

        return true;
    }

    public static function className(string $value): string
    {
        return 'x-' . str_pad(base_convert(hash('crc32b', $value), 16, 36), 7, '0', STR_PAD_LEFT);
    }

    /** @return list<array{0:string,1:string}> [property, value] pairs, split on ; outside brackets and quotes */
    public static function declarations(string $style): array
    {
        $style = html_entity_decode($style, ENT_QUOTES | ENT_HTML5, 'UTF-8');
        $out = [];
        $depth = 0;
        $quote = null;
        $buf = '';
        for ($i = 0, $n = strlen($style); $i <= $n; $i++) {
            $ch = $i < $n ? $style[$i] : ';';
            if ($quote !== null) {
                $quote = $ch === $quote ? null : $quote;
            } elseif ($ch === '"' || $ch === "'") {
                $quote = $ch;
            } elseif ($ch === '(') {
                $depth++;
            } elseif ($ch === ')') {
                $depth = max(0, $depth - 1);
            } elseif ($ch === ';' && $depth === 0) {
                if (($p = strpos($buf, ':')) !== false && trim(substr($buf, 0, $p)) !== '') {
                    $out[] = [trim(substr($buf, 0, $p)), trim(substr($buf, $p + 1))];
                }
                $buf = '';

                continue;
            }
            $buf .= $ch;
        }

        return $out;
    }

    /** @param array<string,string> $map */
    public static function cssFor(array $map): string
    {
        $css = '';
        foreach ($map as $value => $class) {
            $decls = array_map(function ($d) {
                [$prop, $val] = $d;

                return $prop . ':' . (preg_match('/!\s*important$/i', $val) ? $val : $val . ' !important');
            }, self::declarations($value));
            $css .= '.' . $class . '{' . implode(';', $decls) . "}\n";
        }

        return $css;
    }

    /**
     * Copies of the style.css rules that select on the style attribute, with each [style] / [style*="…"]
     * replaced by the classes whose style value it would have matched. Keeps @media wrappers.
     *
     * @param  array<string,string>  $map
     */
    public static function attributeRules(string $css, array $map): string
    {
        $css = preg_replace('#/\*.*?\*/#s', '', $css);
        $out = '';
        foreach (self::rules($css) as [$media, $selectors, $body]) {
            if (! str_contains($selectors, '[style')) {
                continue;
            }
            $rewritten = [];
            foreach (self::splitTopLevel($selectors) as $selector) {
                if (! str_contains($selector, '[style')) {
                    continue;
                }
                $ok = true;
                $new = preg_replace_callback('#\[style(?:\s*\*=\s*(?:"([^"]*)"|\'([^\']*)\'))?\s*\]#', function ($m) use ($map, &$ok) {
                    $needle = ($m[1] ?? '') !== '' ? $m[1] : ($m[2] ?? null);
                    $classes = [];
                    foreach ($map as $value => $class) {
                        if ($needle === null || str_contains(html_entity_decode($value, ENT_QUOTES | ENT_HTML5, 'UTF-8'), $needle)) {
                            $classes[] = '.' . $class;
                        }
                    }
                    if ($classes === []) {
                        $ok = false;

                        return $m[0];
                    }

                    return ':is(' . implode(',', $classes) . ')';
                }, trim($selector));
                if ($ok && ! str_contains($new, '[style')) {
                    $rewritten[] = $new;
                }
            }
            if ($rewritten !== []) {
                $rule = implode(',', $rewritten) . '{' . trim($body) . '}';
                $out .= ($media !== null ? $media . '{' . $rule . '}' : $rule) . "\n";
            }
        }

        return $out;
    }

    /** @return list<array{0:?string,1:string,2:string}> [@media prelude or null, selector list, declarations] */
    private static function rules(string $css): array
    {
        $rules = [];
        $len = strlen($css);
        $i = 0;
        $media = null;
        while ($i < $len) {
            $open = strpos($css, '{', $i);
            $close = strpos($css, '}', $i);
            if ($close !== false && ($open === false || $close < $open)) {
                $media = null; // end of an @media block
                $i = $close + 1;

                continue;
            }
            if ($open === false) {
                break;
            }
            $prelude = trim(substr($css, $i, $open - $i));
            if (str_starts_with($prelude, '@media') || str_starts_with($prelude, '@supports')) {
                $media = $prelude;
                $i = $open + 1;

                continue;
            }
            $end = self::matchingBrace($css, $open);
            if (! str_starts_with($prelude, '@')) {
                $rules[] = [$media, $prelude, substr($css, $open + 1, $end - $open - 1)];
            }
            $i = $end + 1;
        }

        return $rules;
    }

    private static function matchingBrace(string $css, int $open): int
    {
        $depth = 0;
        for ($i = $open, $n = strlen($css); $i < $n; $i++) {
            if ($css[$i] === '{') {
                $depth++;
            } elseif ($css[$i] === '}' && --$depth === 0) {
                return $i;
            }
        }

        return $n - 1;
    }

    /** @return list<string> */
    private static function splitTopLevel(string $selectors): array
    {
        $parts = [];
        $depth = 0;
        $buf = '';
        foreach (str_split($selectors) as $ch) {
            if ($ch === '(' || $ch === '[') {
                $depth++;
            } elseif ($ch === ')' || $ch === ']') {
                $depth--;
            } elseif ($ch === ',' && $depth === 0) {
                $parts[] = $buf;
                $buf = '';

                continue;
            }
            $buf .= $ch;
        }
        $parts[] = $buf;

        return $parts;
    }

    public static function withoutBlock(string $css): string
    {
        $start = strpos($css, self::BEGIN);

        return $start === false ? $css : rtrim(substr($css, 0, $start)) . "\n";
    }

    /** @return list<string> */
    private function readDir(string $dir): array
    {
        return array_map('file_get_contents', glob(rtrim($dir, '/\\') . '/*.html') ?: []);
    }

    /** @return list<string> */
    private function fetchSite(string $base): array
    {
        $urls = [];
        $queue = [$base . '/sitemap.xml'];
        while ($sitemap = array_shift($queue)) {
            preg_match_all('#<loc>(.*?)</loc>#', (string) Http::timeout(30)->get($sitemap)->body(), $m);
            foreach ($m[1] as $loc) {
                str_ends_with($loc, '.xml') ? $queue[] = $loc : $urls[$loc] = true;
            }
        }
        $urls = array_keys($urls);
        $this->info('Fetching ' . count($urls) . ' pages from ' . $base);

        $pages = [];
        foreach (array_chunk($urls, 8) as $chunk) {
            $responses = Http::pool(fn ($pool) => array_map(fn ($u) => $pool->timeout(60)->get($u), $chunk));
            foreach ($responses as $i => $response) {
                if ($response instanceof \Illuminate\Http\Client\Response && $response->successful()) {
                    $pages[] = $response->body();
                } else {
                    $this->warn('Could not fetch ' . $chunk[$i]);
                }
            }
        }

        return $pages;
    }
}
